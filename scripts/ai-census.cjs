#!/usr/bin/env node
/**
 * AI census: every network touchpoint in src/** vs. the functions behind it.
 *   node scripts/ai-census.cjs            -> writes docs/AI_CENSUS.md, exits 0
 *   node scripts/ai-census.cjs --check    -> exits 1 on any PENDING_AI or MISSING touchpoint
 * Classes: STREAM (dual-mode / SSE) | NON_AI (data op, listed in scripts/ai-census-nonai.txt or no AI signature on Netlify)
 *          PENDING_AI (edge function the UI presents as AI but that neither streams nor is a data op) | MISSING (function does not exist)
 */
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const read = (p) => fs.readFileSync(p, 'utf8');

function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (e.name === 'node_modules' || e.name === 'tests' || e.name.startsWith('.')) continue;
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else if (/\.(ts|tsx|js|jsx)$/.test(e.name) && !/\.test\./.test(e.name)) out.push(p);
  }
  return out;
}

// ---- functions
const netlify = {};
for (const f of fs.readdirSync(path.join(root, 'netlify/functions'))) {
  if (f.startsWith('_') || !/\.(js|ts)$/.test(f)) continue;
  netlify[f.replace(/\.(js|ts)$/, '')] = read(path.join(root, 'netlify/functions', f));
}
const edge = {};
const edgeDir = path.join(root, 'supabase/functions');
for (const d of fs.readdirSync(edgeDir)) {
  if (d.startsWith('_')) continue;
  const f = path.join(edgeDir, d, 'index.ts');
  if (fs.existsSync(f)) edge[d] = read(f);
}
const nonAi = new Map();
const nonAiFile = path.join(__dirname, 'ai-census-nonai.txt');
if (fs.existsSync(nonAiFile)) for (const l of read(nonAiFile).split('\n')) {
  const m = /^\s*([a-z0-9-]+)\s*(?:#\s*(.*))?$/.exec(l);
  if (m && !l.trim().startsWith('#')) nonAi.set(m[1], m[2] || '');
}

const NL_STREAM = /runDual|stream\(|text\/event-stream|toSseReadable|streamBackgroundJob/;
const NL_AI = /createResponse|callOpenAI|responsesFetch|streamResponse|@openai\/agents|runSdrAgent|createSdrHandler|runDual/;
const EDGE_STREAM = /respondDual|toSseStream|respondDualTask/;
const EDGE_AI = /_shared\/openai|api\.openai\.com/;

function classify(name) {
  if (netlify[name] !== undefined) {
    const s = netlify[name];
    if (NL_STREAM.test(s) && NL_AI.test(s)) return { cls: 'STREAM', where: 'netlify' };
    if (NL_AI.test(s)) return { cls: nonAi.has(name) ? 'NON_AI' : 'PENDING_AI', where: 'netlify', note: nonAi.get(name) };
    return { cls: 'NON_AI', where: 'netlify', note: 'no AI call' };
  }
  if (edge[name] !== undefined) {
    const s = edge[name];
    if (EDGE_STREAM.test(s)) return { cls: 'STREAM', where: 'edge' };
    if (nonAi.has(name)) return { cls: 'NON_AI', where: 'edge', note: nonAi.get(name) };
    return { cls: 'PENDING_AI', where: 'edge', note: EDGE_AI.test(s) ? 'calls OpenAI without streaming' : 'no AI inside (rule-based) but presented as AI' };
  }
  return { cls: 'MISSING', where: '-' };
}

// ---- touchpoints
const patterns = [
  /\/\.netlify\/functions\/([a-z0-9-]+)/g,
  /functions\.invoke\(\s*['"`]([a-z0-9-]+)/g,
  /callEdgeFunction\(\s*['"`]([a-z0-9-]+)/g,
  /callNetlifyFunction\(\s*['"`]([a-z0-9-]+)/g,
  /functions\/v1\/([a-z0-9-]+)/g,
];
const touch = new Map(); // name -> Set(files)
for (const file of walk(path.join(root, 'src'))) {
  const src = read(file);
  for (const re of patterns) {
    re.lastIndex = 0;
    let m;
    while ((m = re.exec(src))) {
      if (!touch.has(m[1])) touch.set(m[1], new Set());
      touch.get(m[1]).add(path.relative(root, file));
    }
  }
}

const rows = [...touch.entries()].sort().map(([name, files]) => ({ name, files: [...files], ...classify(name) }));
const by = (c) => rows.filter((r) => r.cls === c);
const bad = [...by('PENDING_AI'), ...by('MISSING')];

let md = `# AI census (generated by scripts/ai-census.cjs — do not edit)\n\n`;
md += `Touchpoints: ${rows.length} | STREAM ${by('STREAM').length} | NON_AI ${by('NON_AI').length} | **PENDING_AI ${by('PENDING_AI').length}** | **MISSING ${by('MISSING').length}**\n\n`;
for (const c of ['PENDING_AI', 'MISSING', 'STREAM', 'NON_AI']) {
  md += `## ${c}\n\n| function | where | note | called from |\n|---|---|---|---|\n`;
  for (const r of by(c)) md += `| \`${r.name}\` | ${r.where} | ${r.note || ''} | ${r.files.slice(0, 3).join(', ')}${r.files.length > 3 ? ` (+${r.files.length - 3})` : ''} |\n`;
  md += '\n';
}
fs.mkdirSync(path.join(root, 'docs'), { recursive: true });
fs.writeFileSync(path.join(root, 'docs/AI_CENSUS.md'), md);

console.log(`census: ${rows.length} touchpoints | STREAM ${by('STREAM').length} | NON_AI ${by('NON_AI').length} | PENDING_AI ${by('PENDING_AI').length} | MISSING ${by('MISSING').length}`);
if (process.argv.includes('--check') && bad.length) {
  for (const r of bad) console.log(`  ✗ ${r.cls.padEnd(10)} ${r.name} (${r.where}) <- ${r.files[0]}`);
  process.exit(1);
}
